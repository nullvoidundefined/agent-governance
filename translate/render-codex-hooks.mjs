// render-codex-hooks.mjs: derives codex/hooks.json (the adapter wiring Codex
// runs hooks through) and codex/PORT-STATUS.md (the human-readable audit of
// every settings.json hook registration) from claude/settings.json and the
// port map, so neither file drifts from what settings.json actually
// registers.
import { renderGeneratedHeader, hookNameFromCommand, isHookPorted, isRegistrationPorted } from "./parse-sources.mjs";

const HOOKS_JSON_DESCRIPTION = "Claude Code hooks under Codex; generated by translate/codex.mjs from settings.json";
const ADAPTER_COMMAND = "~/.codex/hooks/codex-hook-adapter.sh";
const DEFAULT_TIMEOUT = 60;

// firstSetting(hooks, key): the value of `key` on the first entry in `hooks`
// (settings.json registration order) that sets it, or undefined when none
// do. hooks.json's timeout and statusMessage carry from this first setter,
// never a per-hook value, since the adapter invocation is one process for
// the whole group.
function firstSetting(hooks, key) {
  for (const hook of hooks) {
    if (hook[key] !== undefined) return hook[key];
  }
  return undefined;
}

// buildHookEntry(group, settingsHooks, portMap): one hooks.json adapter
// entry for a single event+matcher group, or null when the group has no
// ported hooks (the caller drops it). Hook names stay in settings.json
// registration order; timeout and statusMessage carry from the group's
// first setter (timeout defaulting to 60).
function buildHookEntry(group, settingsHooks, portMap) {
  const groupHooks = group.hooks ?? [];
  const portedNames = groupHooks
    .filter((hook) => isHookPorted(hookNameFromCommand(hook.command), settingsHooks, portMap))
    .map((hook) => hookNameFromCommand(hook.command));
  if (portedNames.length === 0) return null;
  const timeout = firstSetting(groupHooks, "timeout") ?? DEFAULT_TIMEOUT;
  const statusMessage = firstSetting(groupHooks, "statusMessage");
  const entry = {};
  if (group.matcher) entry.matcher = group.matcher;
  entry.hooks = [
    {
      type: "command",
      command: `${ADAPTER_COMMAND} ${portedNames.join(" ")}`,
      timeout,
      ...(statusMessage !== undefined ? { statusMessage } : {}),
    },
  ];
  return entry;
}

// renderHooksConfig(settingsHooks, portMap) -> { path: "hooks.json", content
// }: one adapter entry per event+matcher group that has at least one ported
// hook. Events whose port-map translation is null are skipped outright; an
// event that ends up with no surviving groups never appears in the output.
export function renderHooksConfig(settingsHooks, portMap) {
  const hooks = {};
  for (const [event, groups] of Object.entries(settingsHooks)) {
    const translatedEvent = portMap.events[event];
    if (translatedEvent == null) continue;
    for (const group of groups) {
      const entry = buildHookEntry(group, settingsHooks, portMap);
      if (entry) (hooks[translatedEvent] ??= []).push(entry);
    }
  }
  const content = `${JSON.stringify({ description: HOOKS_JSON_DESCRIPTION, hooks }, null, 2)}\n`;
  return { path: "hooks.json", content };
}

// formatClaudeCodeEvent(event, matcher): the "Claude Code event" column,
// e.g. "PreToolUse (Bash)" when the registration carries a matcher, else
// just "PreToolUse".
function formatClaudeCodeEvent(event, matcher) {
  return matcher ? `${event} (${matcher})` : event;
}

// formatUnderCodex(hookName, event, matcher, portMap): the "Under Codex"
// column for one registration row. Ported rows name the translated event
// and, when set, the matcher; unported rows carry the hook's reason from
// the port map, falling back to a generic "no Codex equivalent" message
// naming the Claude Code event that has none.
function formatUnderCodex(hookName, event, matcher, portMap) {
  if (isRegistrationPorted(hookName, event, portMap)) {
    const matcherClause = matcher ? ` (matcher \`${matcher}\`)` : "";
    return `ported: \`${portMap.events[event]}\`${matcherClause}`;
  }
  const reason = portMap.unported_reasons[hookName] ?? `the ${event} event has no Codex equivalent.`;
  return `not ported: ${reason}`;
}

// buildRegistrationRows(settingsHooks, portMap): one row per settings.json
// hook registration, in registration order, carrying everything the table
// and the summary counts need.
function buildRegistrationRows(settingsHooks, portMap) {
  const rows = [];
  for (const [event, groups] of Object.entries(settingsHooks)) {
    for (const group of groups) {
      for (const hook of group.hooks ?? []) {
        const hookName = hookNameFromCommand(hook.command);
        rows.push({
          hookName,
          event,
          matcher: group.matcher ?? "",
          ported: isRegistrationPorted(hookName, event, portMap),
          translatedEvent: portMap.events[event],
        });
      }
    }
  }
  return rows;
}

// renderPortStatusTable(rows, portMap): the Markdown table body, one row per
// registration, in the order buildRegistrationRows produced them.
function renderPortStatusTable(rows, portMap) {
  return [
    "| Hook | Claude Code event | Under Codex |",
    "|---|---|---|",
    ...rows.map((row) =>
      `| \`${row.hookName}\` | ${formatClaudeCodeEvent(row.event, row.matcher)} | ${formatUnderCodex(row.hookName, row.event, row.matcher, portMap)} |`,
    ),
  ].join("\n");
}

// renderPortStatus(settingsHooks, portMap) -> { path: "PORT-STATUS.md",
// content }: one table row per settings.json registration, plus a summary
// line whose counts are computed from the same rows it renders, never
// hand-typed. A non-empty portMap.port_status_appendix (the hand-authored
// Permission-rules prose the generator cannot derive) appends verbatim
// after the table.
export function renderPortStatus(settingsHooks, portMap) {
  const rows = buildRegistrationRows(settingsHooks, portMap);
  const portedRows = rows.filter((row) => row.ported);
  const codexEventCount = new Set(portedRows.map((row) => row.translatedEvent)).size;
  const summaryLine = `${portedRows.length} of ${rows.length} hook registrations port, across ${codexEventCount} Codex events.`;
  const appendix = portMap.port_status_appendix ? `\n\n${portMap.port_status_appendix}` : "";
  const content =
    `${renderGeneratedHeader("settings.json")}\n\n# Codex port status\n\n${summaryLine}\n\n${renderPortStatusTable(rows, portMap)}${appendix}\n`;
  return { path: "PORT-STATUS.md", content };
}
